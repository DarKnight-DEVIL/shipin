/**
 * Walks `src/app/api` and renders the route manifest the app imports.
 *
 * This lives in `scripts/` rather than in `src/` on purpose. `node:fs` plus a
 * path computed at runtime is something Turbopack cannot resolve, so it falls
 * back to tracing the *whole* project into the standalone output — `.next/
 * standalone` carried 450 source files for a check that cannot even run there
 * (a standalone build ships without `src/`). The walk now happens at build
 * time, and the server bundle only sees a static array of strings.
 */
import { readdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/** `<app>/src/app/api`, resolved from this file, not from the working directory. */
export const API_ROUTE_DIR = fileURLToPath(
  new URL("../../src/app/api", import.meta.url)
);

/** The manifest module `routeClassification.ts` imports. */
export const MANIFEST_PATH = fileURLToPath(
  new URL("../../src/config/apiRoutes.generated.ts", import.meta.url)
);

const ROUTE_FILENAMES = new Set([
  "route.ts",
  "route.tsx",
  "route.js",
  "route.jsx",
  "route.mts",
  "route.mjs",
]);

/**
 * URL path of every App Router route handler under `apiDir`.
 *
 * Route groups — `(group)` segments — are not part of the URL and are dropped;
 * dynamic segments are kept literally, which is what the classifier sees when
 * it prefix-matches a real request path.
 */
export function collectApiRoutePaths(apiDir = API_ROUTE_DIR) {
  const routes = [];

  const walk = (dir, segments) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (entry.isDirectory()) {
        const isRouteGroup = /^\(.+\)$/.test(entry.name);
        walk(
          path.join(dir, entry.name),
          isRouteGroup ? segments : [...segments, entry.name]
        );
        continue;
      }

      if (ROUTE_FILENAMES.has(entry.name)) {
        routes.push(`/${segments.join("/")}`);
      }
    }
  };

  // Seed with the directory's own name: the caller passes the `api` folder
  // itself, and the URL starts with `/api`.
  walk(apiDir, [path.basename(apiDir)]);
  return routes.sort();
}

/** The exact contents of the manifest module for `routes`. */
export function buildManifestSource(routes) {
  const entries = routes
    .map((route) => `  ${JSON.stringify(route)},`)
    .join("\n");

  return `/**
 * Every handler under \`src/app/api\`, for the boot-time classification check.
 *
 * Generated by \`npm run gen:api-routes\` — do not edit by hand. The walk needs
 * \`node:fs\` and a runtime path, which makes Turbopack trace the whole project
 * into the standalone output, so it runs at build time instead and the server
 * bundle only sees this array. \`scripts/lib/api-routes.test.ts\` fails when the
 * file is stale, so a new route cannot be forgotten.
 */
export const API_ROUTE_PATHS: readonly string[] = [
${entries}
];
`;
}
