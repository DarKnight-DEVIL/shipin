#!/usr/bin/env node
/**
 * Renders `docs/API.md` — the route inventory with the auth class each route
 * actually receives.
 *
 * Two sources, both of which already exist for the runtime:
 *
 *   - `src/app/api/**` gives the routes, through the same walk the boot-time
 *     classifier uses (`scripts/lib/api-routes.mjs`), so the doc cannot list a
 *     route that does not exist.
 *   - `src/config/routeAuth.ts` gives the classification table and the
 *     exact-match exceptions, parsed as text because this script runs in Node
 *     and the table lives in TypeScript.
 *
 * The parsed values are not trusted blindly: `src/config/apiDocs.test.ts`
 * compares every documented row against `classifyRoute()` from the real module,
 * so a parsing mistake shows up as a failed test instead of a wrong document.
 * That test is the reason the prefix rule is duplicated here at all — this
 * script has to *decide* something, and the test proves the decisions match.
 *
 * Usage:
 *   node scripts/gen-api-docs.mjs            # rewrite docs/API.md
 *   node scripts/gen-api-docs.mjs --check    # exit 1 if the file is stale
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { collectApiRoutePaths } from "./lib/api-routes.mjs";

const AUTH_SOURCE = fileURLToPath(
  new URL("../src/config/routeAuth.ts", import.meta.url)
);
const DOC_PATH = fileURLToPath(new URL("../../../docs/API.md", import.meta.url));

const source = readFileSync(AUTH_SOURCE, "utf8");

/** `"/api/x": "customer",` entries of ROUTE_AUTH_CLASSIFICATION. */
function parseClassification(text) {
  const table = text.match(
    /export const ROUTE_AUTH_CLASSIFICATION[^=]*=\s*\{([\s\S]*?)\n\};/
  )?.[1];

  if (!table) {
    throw new Error(
      "gen-api-docs: could not read ROUTE_AUTH_CLASSIFICATION from routeAuth.ts. Nothing was generated."
    );
  }

  const entries = [
    ...table.matchAll(/"(\/api[^"]*)"\s*:\s*"(public|customer|admin)"/g),
  ].map(([, route, auth]) => [route, auth]);

  if (entries.length < 10) {
    throw new Error(
      `gen-api-docs: parsed only ${entries.length} classifications; refusing to write a document that checks nothing.`
    );
  }

  return entries;
}

/** Prefixes carved out of a protected prefix; they must not cover children. */
function parseExactOnly(text) {
  const set = text.match(/const EXACT_ONLY[^=]*=\s*new Set\(\[([\s\S]*?)\]\)/)?.[1];

  if (set === undefined) {
    throw new Error(
      "gen-api-docs: could not read EXACT_ONLY from routeAuth.ts. Nothing was generated."
    );
  }

  return new Set([...set.matchAll(/"(\/api[^"]*)"/g)].map(([, route]) => route));
}

const classification = parseClassification(source);
const exactOnly = parseExactOnly(source);

/** Same rule as `classifyRoute`: exact entry wins, else the longest prefix. */
function effectiveAuth(pathname) {
  const exact = classification.find(([route]) => route === pathname)?.[1];
  if (exact) return exact;

  let match = "unclassified";
  let matchLength = -1;

  for (const [route, auth] of classification) {
    if (exactOnly.has(route)) continue;
    if (pathname.startsWith(route) && route.length > matchLength) {
      match = auth;
      matchLength = route.length;
    }
  }

  return match;
}

const routes = collectApiRoutePaths();

// A route with no classification would answer 500 at boot in production, so it
// must never reach the document as if it were fine.
const unclassified = routes.filter((route) => effectiveAuth(route) === "unclassified");

if (unclassified.length > 0) {
  console.error(
    `gen-api-docs: ${unclassified.length} route(s) have no classification: ${unclassified.join(", ")}`
  );
  process.exit(1);
}

const rows = routes
  .map((route) => `| \`${route}\` | ${effectiveAuth(route)} |`)
  .join("\n");

const document = `# API — route contract

<!-- Generated by \`npm run gen:api-docs\` from src/app/api/** and
     src/config/routeAuth.ts. The table is checked by src/config/apiDocs.test.ts;
     edit the sources, not the rows. -->

The conventions every route shares: how a caller is authenticated, what an error
looks like, and which routes exist with which class. Request and response bodies
are typed in \`src/types/**\` and each route handler is the authority on its own
body — this document is the part that is the same everywhere.

## Authentication classes

The proxy checks for the credential; the handler does the real verification.

| Class | The proxy requires | The handler does |
| --- | --- | --- |
| \`public\` | nothing | authenticates itself (cron \`CRON_SECRET\` HMAC, PayPal webhook signature, signed unsubscribe token) or is genuinely anonymous |
| \`customer\` | \`Authorization: Bearer <Firebase ID token>\` | verifies the token and a verified email |
| \`admin\` | the same bearer token | \`requireAdmin\`: admin role **and** an MFA elevation cookie |

Matching is by path: an exact entry wins, otherwise the longest prefix. Cron and
unsubscribe routes are listed exactly and are **not** inherited by their children
(\`EXACT_ONLY\` in \`src/config/routeAuth.ts\`) — a route under
\`/api/admin/requests/quotes/expire\` does not become public.

A route the table does not classify fails the boot-time check, so
\`unclassified\` never reaches production.

## Error envelope

Handlers wrapped in \`withErrorHandler\` answer with this shape and the status of
the thrown error:

\`\`\`json
{ "success": false, "error": "Request not found.", "code": "NOT_FOUND" }
\`\`\`

\`code\` and \`details\` are optional. Codes the edge can return before a handler
runs: \`AUTHENTICATION_REQUIRED\` (401), \`RATE_LIMIT_ERROR\` (429),
\`ROUTE_UNCLASSIFIED\` (500). \`success\` is present on every error body because
clients branch on it rather than on the status alone.

## Headers

- \`Authorization: Bearer <ID token>\` — \`customer\` and \`admin\` routes.
- \`X-Firebase-AppCheck: <token>\` — sent by the browser; verified server-side
  when \`APP_CHECK_ENFORCEMENT\` is on. The Admin SDK bypasses Firebase's own
  enforcement, so this header is the only thing enforcing it for our routes.
- Cron routes authenticate with a timestamp plus an HMAC of it signed with
  \`CRON_SECRET\`, not with a session.

## Routes

${routes.length} route handlers:

| Route | Auth |
| --- | --- |
${rows}
`;

const existing = (() => {
  try {
    return readFileSync(DOC_PATH, "utf8");
  } catch {
    return null;
  }
})();

if (process.argv.includes("--check")) {
  if (existing !== document) {
    console.error(
      "gen-api-docs: docs/API.md is stale. Run `npm run gen:api-docs` and commit the result."
    );
    process.exit(1);
  }
  console.log(`docs/API.md is current (${routes.length} routes).`);
  process.exit(0);
}

writeFileSync(DOC_PATH, document);
console.log(`Wrote docs/API.md (${routes.length} routes).`);
